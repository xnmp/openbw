"""Generate ui/order_names.h: display names for the Orders enum in bwenums.h, for the
selection panel ("AttackUnit" -> "Attack Unit"). Rerun if bwenums.h changes.

  python3 viewer/gen_order_names.py bwenums.h ui/order_names.h
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
body = re.search(r"enum struct Orders\s*:\s*int\s*\{(.*?)\};", open(src).read(), re.S).group(1)
names = [n.strip() for n in re.sub(r"//.*", "", body).split(",") if n.strip()]
assert all("=" not in n for n in names), "Orders must stay a plain sequential enum"


def spaced(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", name)


with open(out, "w") as f:
    f.write("// Generated by viewer/gen_order_names.py from bwenums.h (enum struct Orders).\n")
    f.write("#pragma once\nnamespace order_names {\n")
    f.write(f"constexpr int count = {len(names)};\n")
    f.write("constexpr const char* names[count] = {\n")
    f.writelines(f'\t"{spaced(n)}",\n' for n in names)
    f.write("};\n}\n")
