"""Generate ui/hud_font.h: an 8-bit-alpha bitmap of printable ASCII
from a monospace TTF, for the replay viewer's stats overlay. Run once; the header is
self-contained so the viewer has no runtime font dependency.

  uv run --no-project --with pillow python viewer/gen_hud_font.py \
      /usr/share/fonts/TTF/JetBrainsMono-Bold.ttf 16 ui/hud_font.h
JetBrains Mono is SIL OFL 1.1; the bitmaps are a derived rendering of it.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
font = ImageFont.truetype(ttf, size)
ascent, descent = font.getmetrics()
cell_w = max(int(round(font.getlength(chr(c)))) for c in range(32, 127))
cell_h = ascent + descent
rows = []
for c in range(32, 127):
    img = Image.new("L", (cell_w, cell_h), 0)
    ImageDraw.Draw(img).text((0, 0), chr(c), font=font, fill=255)
    rows.append(list(img.tobytes()))
with open(out, "w") as f:
    f.write(f"// Generated by viewer/gen_hud_font.py from {ttf.rsplit('/', 1)[-1]} at {size}px.\n")
    f.write("// JetBrains Mono: SIL Open Font License 1.1. Glyphs for ASCII 32..126, 8-bit coverage.\n")
    f.write("#pragma once\n#include <cstdint>\nnamespace hud_font {\n")
    f.write(f"constexpr int cell_w = {cell_w};\nconstexpr int cell_h = {cell_h};\n")
    f.write(f"constexpr uint8_t glyphs[95][{cell_w * cell_h}] = {{\n")
    for r in rows:
        f.write("{" + ",".join(map(str, r)) + "},\n")
    f.write("};\n}\n")
print(cell_w, cell_h)
